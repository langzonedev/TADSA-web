import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {seed} from '../seed.mjs';
import {normalise,dispatch} from '../device-model.mjs';
import '../device-extensions.mjs';
test('availability overwrite, split, clear, stale revision and replay',async()=>{
 const d=normalise(seed({enriched:false}));
 const read=async id=>structuredClone(dispatch(d,'availability/'+id));
 const save=async(id,input)=>structuredClone(dispatch(d,'availability/'+id+'/entries','POST',input));
 const rejects=assert.rejects;
  const person='person-3';
  let current=await read(person);
  const put=async(startDate,endDate,status='available',patch={})=>{const input={requestId:randomUUID(),id:null,version:0,calendarVersion:current.version,startDate,endDate,status,note:'Synthetic range test',...patch};current=await save(person,input);return input;};
  await put('2028-02-27','2028-03-04');
  const weekVersion=current.version;
  const day=await put('2028-02-29','2028-02-29','unavailable');
  const view=()=>current.entries.map(({startDate,endDate,status})=>[startDate,endDate,status]);
  assert.deepEqual(view(),[['2028-02-27','2028-02-28','available'],['2028-02-29','2028-02-29','unavailable'],['2028-03-01','2028-03-04','available']]);
  assert.deepEqual(await save(person,day),current);
  await rejects(()=>save(person,{...day,requestId:randomUUID(),calendarVersion:weekVersion}),e=>e.code==='VERSION_CONFLICT');
  assert.deepEqual(await read(person),current);
  const snapshot=structuredClone(current);
  await rejects(()=>save(person,{...day,requestId:randomUUID(),calendarVersion:current.version,endDate:'2028-02-28'}),e=>e.status===422);
  assert.deepEqual(await read(person),snapshot);
  await put('2028-02-28','2028-03-02','limited');
  assert.deepEqual(view(),[['2028-02-27','2028-02-27','available'],['2028-02-28','2028-03-02','limited'],['2028-03-03','2028-03-04','available']]);
  await put('2028-02-29','2028-03-01','unknown');
  assert.deepEqual(view(),[['2028-02-27','2028-02-27','available'],['2028-02-28','2028-02-28','limited'],['2028-03-02','2028-03-02','limited'],['2028-03-03','2028-03-04','available']]);
  assert.ok(current.entries.every(e=>e.note==='Synthetic range test'));
  const old=current.entries[0];
  await put('2028-02-27','2028-03-04','available');
  await rejects(()=>save(person,{...day,requestId:randomUUID(),calendarVersion:current.version,id:old.id,version:old.version}),e=>e.status===404||e.code==='VERSION_CONFLICT');
  const edited=current.entries[0];
  await put('2028-03-01','2028-03-06','unavailable',{id:edited.id,version:edited.version});
  assert.deepEqual(view(),[['2028-03-01','2028-03-06','unavailable']]);
  await put('2028-01-01','2028-12-31','unknown');
  assert.deepEqual(current.entries,[]);
});
