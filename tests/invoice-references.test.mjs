test('project finance evidence preserves explicit No, independent workflow, original files and backup validation',async()=>{
 const data=normalise(seed({enriched:false}));
 const path='projects/project-1/finance-status',life='projects/project-1/lifecycle';
 const call=(path,method='GET',input={},actor=null)=>dispatch(data,path,method,input,new URLSearchParams(),actor);
 const action=(name,details)=>call(life,'PUT',{requestId:crypto.randomUUID(),version:call(life).version,action:name,data:details});
 action('begin',{});
 const before=call(path);
 assert.equal(before.paidInFull,null);
 const input={...emptyFinanceStatus,requestId:crypto.randomUUID(),version:before.version,
  invoiceSentOn:'2025-10-02',invoiceNumber:'001',paidInFull:false,paidStatusOn:'2025-10-04'};
 const saved=call(path,'PUT',input);
 assert.deepEqual(call(path,'PUT',input),saved);
 assert.throws(()=>call(path,'PUT',input,{role:'coordinator'}),error=>error.status===403);
 assert.throws(()=>call(path,'PUT',{...input,requestId:crypto.randomUUID()}),error=>error.status===409);
 assert.equal(call(life).state.stage,'enquiry');
 assert.equal(action('cancel',{reason:'Synthetic cancellation'}).state.stage,'finance_handoff');
 const addFile=id=>call('projects/'+id+'/attachments','POST',{requestId:crypto.randomUUID(),name:'synthetic.pdf',mime:'application/pdf',dataBase64:btoa('%PDF-1.4\n%%EOF')});
 const source=addFile('project-1'),wrongFile=addFile('project-2');
 const cost={receivedOn:'2025-10-05',lines:[],notes:'No charge on the synthetic return.'};
 assert.throws(()=>action('costReturn',{...cost,sourceFileId:wrongFile.id}),error=>error.status===422);
 const revision=action('costReturn',{...cost,sourceFileId:source.id}).state.costReturns[0];
 assert.equal(revision.sourceFileName,source.name);
 assert.equal(revision.receivedOn,cost.receivedOn);
 action('costReturn',cost);
 assert.throws(()=>call('projects/project-1/attachments/'+source.id+'/remove','POST',{requestId:crypto.randomUUID(),version:1}),/retained/);
 assert.deepEqual((await validateBackup(data)).financeStatuses,data.financeStatuses);
 const bad=structuredClone(data);
 bad.attachments['project-1'][0].removed=true;
 await assert.rejects(validateBackup(bad),/original cost return/);
 data.financeStatuses['project-1'].paidStatusOn='';
 await assert.rejects(validateBackup(data),/date together/);
});
